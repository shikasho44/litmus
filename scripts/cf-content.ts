/**
 * Writes server/cloudflare/content.generated.ts: static JSON imports of every case file plus the
 * line bank and prologue, which the Cloudflare Worker bundles (Workers have no file system, so
 * server/node/content-fs.ts cannot be used there). Same folder rules as content-fs.ts.
 *
 *   npx tsx scripts/cf-content.ts            write the module (npm run cf:content)
 *   npx tsx scripts/cf-content.ts --check    exit 1 when it is out of date
 *
 * `npm run deploy:cf` runs it before every deploy; tests/cloudflare/worker.test.ts fails when a
 * case folder was added or removed without regenerating.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const GENERATED_PATH = 'server/cloudflare/content.generated.ts';

export function workerCaseDirs(contentRoot: string): string[] {
  const dir = join(contentRoot, 'cases');
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true })
    .filter((d) => d.isDirectory() && !d.name.startsWith('.') && !d.name.startsWith('_') && existsSync(join(dir, d.name, 'case.json')))
    .map((d) => d.name)
    .sort();
}

export function renderContentModule(projectRoot: string): string {
  const contentRoot = join(projectRoot, 'content');
  const dirs = workerCaseDirs(contentRoot);
  const hasLines = existsSync(join(contentRoot, 'holma-lines.json'));
  const hasPrologue = existsSync(join(contentRoot, 'prologue.json'));
  const L: string[] = [
    '// GENERATED by scripts/cf-content.ts — do not edit. Regenerate: npm run cf:content',
    '// The content the Cloudflare Worker embeds at build time (Workers have no file system).',
    "import type { RawContent } from '../engine/registry.js';",
  ];
  dirs.forEach((d, i) => L.push(`import case${i} from '../../content/cases/${d}/case.json';`));
  if (hasLines) L.push("import lines from '../../content/holma-lines.json';");
  if (hasPrologue) L.push("import prologue from '../../content/prologue.json';");
  L.push('');
  L.push(`export const CASE_DIRS: readonly string[] = ${JSON.stringify(dirs)};`);
  L.push('');
  L.push('export function rawContent(): RawContent {');
  L.push('  return {');
  L.push('    cases: [');
  dirs.forEach((d, i) => L.push(`      { dir: ${JSON.stringify(d)}, path: ${JSON.stringify(`content/cases/${d}/case.json`)}, data: case${i} as unknown },`));
  L.push('    ],');
  if (hasLines) L.push('    lines: lines as unknown,');
  if (hasPrologue) L.push('    prologue: prologue as unknown,');
  L.push('  };');
  L.push('}');
  L.push('');
  return L.join('\n');
}

function main(): void {
  const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
  const out = join(root, GENERATED_PATH);
  const next = renderContentModule(root);
  const cur = existsSync(out) ? readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : '';
  if (process.argv.includes('--check')) {
    if (cur !== next) {
      console.error(`${GENERATED_PATH} is out of date — run: npm run cf:content`);
      process.exit(1);
    }
    console.log(`${GENERATED_PATH} is up to date`);
    return;
  }
  if (cur === next) {
    console.log(`${GENERATED_PATH} unchanged (${workerCaseDirs(join(root, 'content')).length} cases)`);
    return;
  }
  writeFileSync(out, next, 'utf8');
  console.log(`wrote ${GENERATED_PATH} (${workerCaseDirs(join(root, 'content')).length} cases)`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) main();
