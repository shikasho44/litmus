/**
 * Vite plugin: release guard for the built site (`vite build`, both http and static modes).
 *
 * Everything in public/ and every chunk is world-readable once deployed, so after the bundle
 * is written this scans the output directory and FAILS THE BUILD when:
 *   1. any Markdown file is in it (notes such as art credits describe the solutions);
 *   2. a case secret appears in any text file — victim names/readings, the cause of death,
 *      or a case's leakTerms (content/cases/<id>/case.json). The static build embeds the
 *      engine and all cases in assets/embedded-*.js by design (docs/decisions.md); only that
 *      chunk is exempt, and only in the static build;
 *   3. zod (a `safeParse` call site) is in any chunk other than admin-* / embedded-*: the game
 *      client never validates with zod, and zod's eval probe trips the production CSP.
 * It also emits robots.txt for the http (Vercel) build: /api/, /admin.html and the spoiler
 * images under /cases/ are never crawled, and /art/ is kept out until the official release.
 *
 * Set JANEDOE_RELEASE_GUARD=warn to report without failing (local experiments only).
 * Node-only (used by vite.config.ts, never bundled into the app).
 */
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative, resolve, sep } from 'node:path';
import type { Plugin, ResolvedConfig } from 'vite';

export interface ReleaseGuardOptions {
  /** Static build: the engine + case data live in assets/embedded-*.js on purpose. */
  embedded: boolean;
  /** VITE_OFFICIAL_RELEASE_ENABLED — relaxes robots.txt for /art/. */
  official: boolean;
}

const TEXT_FILE = /\.(html?|m?js|cjs|css|json|txt|md|markdown|svg|xml|webmanifest|map|csv|ya?ml)$/i;
const MARKDOWN = /\.(md|markdown)$/i;
/** Chunks allowed to contain zod: the admin console and the static build's embedded engine. */
const ZOD_ALLOWED = /^assets\/(admin|embedded)-[\w-]+\.js$/;
/** Static build only: the one chunk allowed to carry case data. */
const SECRETS_ALLOWED_STATIC = /^assets\/embedded-[\w-]+\.js(\.map)?$/;
/** Shorter leakTerms are ordinary words ("脱衣", "火照") that UI copy may legitimately use. */
const MIN_LEAK_TERM = 3;

/**
 * Reviewed exceptions, printed as warnings on every build so they stay visible. Keep it short;
 * the real fix is to move the text into case data (served only after the verdict).
 */
const ACCEPTED: { file: RegExp; term: string; why: string }[] = [
  // (empty — the ECG diagram's rhythm label moved into case data on 2026-09-25:
  //  science.diagrams[].rhythmLabel / rhythmDetail in shared/case-schema.ts)
];

interface Secret {
  term: string;
  caseId: string;
  kind: string;
}

function walk(dir: string, out: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

function str(v: unknown): string {
  return typeof v === 'string' ? v.trim() : '';
}

/** Secrets of every case under content/cases (the same files the server reads). */
export function collectCaseSecrets(root: string): Secret[] {
  const dir = resolve(root, 'content', 'cases');
  if (!existsSync(dir)) return [];
  const secrets: Secret[] = [];
  const seen = new Set<string>();
  const add = (term: string, caseId: string, kind: string) => {
    const t = term.trim();
    const key = t.toLowerCase();
    if (!t || seen.has(key)) return;
    seen.add(key);
    secrets.push({ term: t, caseId, kind });
  };
  for (const name of readdirSync(dir)) {
    const file = join(dir, name, 'case.json');
    if (!existsSync(file)) continue;
    let c: Record<string, any>;
    try {
      c = JSON.parse(readFileSync(file, 'utf8'));
    } catch {
      continue; // validate-cases reports broken JSON; not this guard's job
    }
    const id = str(c.id) || name;
    const victim = c.victim ?? {};
    for (const [field, value] of [
      ['victim.name', str(victim.name)],
      ['victim.nameKana', str(victim.nameKana)],
    ] as const) {
      if (!value) continue;
      add(value, id, field);
      // (JS \s includes the ideographic space U+3000)
      add(value.replace(/\s+/g, ''), id, field);
      // family / given name on their own, when they are distinctive enough
      if (field === 'victim.name') for (const part of value.split(/\s+/)) if (part.length >= 2) add(part, id, field);
    }
    const cause = str(c.truth?.causeOfDeath).split(/[（(]/u)[0];
    if (cause.length >= 2) add(cause, id, 'truth.causeOfDeath');
    for (const t of Array.isArray(c.leakTerms) ? c.leakTerms : []) {
      if (typeof t === 'string' && t.trim().length >= MIN_LEAK_TERM) add(t, id, 'leakTerms');
    }
  }
  return secrets;
}

function robotsTxt(official: boolean): string {
  return [
    '# Generated by src/build/release-guard.ts (http build).',
    'User-agent: *',
    'Disallow: /api/',
    'Disallow: /admin.html',
    '# reconstruction panels and victim portraits are spoilers',
    'Disallow: /cases/',
    ...(official ? [] : ['# preview: no image indexing before the official release', 'Disallow: /art/']),
    '',
  ].join('\n');
}

export function releaseGuard(opts: ReleaseGuardOptions): Plugin {
  let config: ResolvedConfig;
  return {
    name: 'janedoe:release-guard',
    apply: 'build',
    configResolved(c) {
      config = c;
    },
    generateBundle() {
      if (opts.embedded) return;
      if (config.publicDir && existsSync(join(config.publicDir, 'robots.txt'))) return; // a hand-written one wins
      this.emitFile({ type: 'asset', fileName: 'robots.txt', source: robotsTxt(opts.official) });
    },
    writeBundle: {
      order: 'post',
      sequential: true,
      handler(options) {
        const outDir = options.dir ?? resolve(config.root, config.build.outDir);
        if (!existsSync(outDir)) return;
        const secrets = collectCaseSecrets(config.root);
        const problems: string[] = [];
        const accepted: string[] = [];
        for (const file of walk(outDir)) {
          const rel = relative(outDir, file).split(sep).join('/');
          if (MARKDOWN.test(rel)) {
            problems.push(`${rel}: Markdown must not ship (keep notes outside public/, e.g. art-src/ or docs/)`);
            continue;
          }
          if (!TEXT_FILE.test(rel)) continue;
          const text = readFileSync(file, 'utf8');
          if (/\.m?js$/.test(rel) && !ZOD_ALLOWED.test(rel) && text.includes('safeParse')) {
            problems.push(`${rel}: contains zod (safeParse). Import enum constants from shared/constants.ts, not shared/case-schema.ts`);
          }
          if (opts.embedded && SECRETS_ALLOWED_STATIC.test(rel)) continue;
          const lower = text.toLowerCase();
          const hits = secrets.filter((s) => {
            if (!lower.includes(s.term.toLowerCase())) return false;
            const ok = ACCEPTED.find((a) => a.term === s.term && a.file.test(rel));
            if (ok) accepted.push(`${rel}: "${s.term}" (${s.caseId}) — ${ok.why}`);
            return !ok;
          });
          if (hits.length) {
            const list = hits.slice(0, 6).map((s) => `"${s.term}" (${s.caseId} ${s.kind})`).join(', ');
            problems.push(`${rel}: case secret(s) ${list}${hits.length > 6 ? ` +${hits.length - 6} more` : ''}`);
          }
        }
        if (accepted.length) config.logger.warn(`[release-guard] accepted exception(s), still visible in the build:\n  - ${accepted.join('\n  - ')}`);
        if (!problems.length) {
          config.logger.info(`[release-guard] ok — ${secrets.length} case secrets, no Markdown, zod only in admin/embedded chunks`);
          return;
        }
        const msg = `[release-guard] ${problems.length} problem(s) in ${relative(config.root, outDir) || outDir}:\n  - ${problems.join('\n  - ')}`;
        if (process.env.JANEDOE_RELEASE_GUARD === 'warn') config.logger.warn(msg);
        else this.error(msg);
      },
    },
  };
}
